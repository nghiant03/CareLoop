def test_postgres_clinical_roundtrip_history_ids_and_racing_edits(pg_databases, monkeypatch):
    from shared.envelope_schema import NutrientEnvelope

    monkeypatch.setenv("CARELOOP_APP_DATABASE_URL", pg_databases["clinical"])
    persistence.init_db()
    record = {"patient_id": "PG-PATIENT", "name": "synthetic"}
    assert persistence.insert_patient(record)
    assert not persistence.insert_patient(record)
    assert persistence.saved_patients() == {"PG-PATIENT": record}
    original = NutrientEnvelope.model_validate({"envelope_id": "ENV-PG-PATIENT-001", "patient_id": "PG-PATIENT",
        "patient_snapshot": {"patient_id": "PG-PATIENT", "age": 60, "sex": "M", "weight_kg": 70},
        "targets": [], "priority_basis": "test"})
    persistence.store_envelope(original, new_proposal=True)
    assert original.lifecycle_revision == 1

    def update(_):
        proposed = original.model_copy(deep=True)
        try:
            persistence.store_envelope(proposed)
            return "saved"
        except persistence.EnvelopeConflictError:
            return "stale"

    with ThreadPoolExecutor(max_workers=2) as workers:
        assert sorted(workers.map(update, range(2))) == ["saved", "stale"]
    assert len(persistence.list_envelope_history("PG-PATIENT")) == 2
    assert persistence.journal_envelope(original, effective_at="2026-01-01") > 0
    persistence.put_log("PG-PATIENT", "2026-01-01", "lunch", "SG0001", items=[{"dish_id":"SG0001", "quantity":1}])
    log = persistence.get_log("PG-PATIENT", "2026-01-01", "lunch")
    assert log is not None and log["items"]
    sim = persistence.save_simulation("PG-PATIENT", original.envelope_id, [], {"test": True})
    assert persistence.list_simulations("PG-PATIENT")[0]["simulation_id"] == sim
    plan = persistence.save_plan("PG-PATIENT", original.envelope_id, 1, "test", True, 0, document={"days":[]})
    saved_plan = persistence.get_plan(plan)
    assert saved_plan is not None and saved_plan["days"] == []
    review = persistence.create_review_item("PG-PATIENT", "test", {})
    persistence.record_review_action(review, "reviewed")
    item = persistence.get_review_item(review)
    assert item is not None and item["action"]["action"] == "reviewed"



-- Version one knowledge journal.
CREATE TABLE knowledge_drafts (
    draft_id TEXT PRIMARY KEY,
    author TEXT NOT NULL,
    created_at TEXT NOT NULL,
    parent_release TEXT,
    provenance_json TEXT NOT NULL
);
CREATE TABLE knowledge_revisions (
    draft_id TEXT NOT NULL REFERENCES knowledge_drafts(draft_id),
    revision INTEGER NOT NULL,
    editor TEXT NOT NULL,
    created_at TEXT NOT NULL,
    rules_json TEXT NOT NULL,
    dishes_json TEXT NOT NULL,
    rules_hash TEXT NOT NULL,
    dishes_hash TEXT NOT NULL,
    validation_json TEXT NOT NULL,
    PRIMARY KEY(draft_id, revision)
);
CREATE TABLE knowledge_reviews (
    draft_id TEXT NOT NULL,
    revision INTEGER NOT NULL,
    reviewer TEXT NOT NULL,
    decision TEXT NOT NULL CHECK(decision IN ('approve','reject')),
    note TEXT NOT NULL,
    reviewed_at TEXT NOT NULL,
    PRIMARY KEY(draft_id, revision),
    FOREIGN KEY(draft_id, revision) REFERENCES knowledge_revisions(draft_id, revision)
);
CREATE TABLE knowledge_releases (
    release_id TEXT PRIMARY KEY,
    draft_id TEXT NOT NULL UNIQUE,
    revision INTEGER NOT NULL,
    publisher TEXT NOT NULL,
    note TEXT NOT NULL,
    published_at TEXT NOT NULL,
    FOREIGN KEY(draft_id, revision) REFERENCES knowledge_reviews(draft_id, revision)
);
CREATE TABLE knowledge_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id TEXT NOT NULL REFERENCES knowledge_drafts(draft_id),
    revision INTEGER NOT NULL,
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    detail_json TEXT NOT NULL,
    created_at TEXT NOT NULL
);

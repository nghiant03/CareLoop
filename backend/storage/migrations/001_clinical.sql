-- Frozen version-1 clinical schema. Future changes require a new migration.
-- Snapshot JSON remains TEXT to preserve exact historical payloads.
CREATE TABLE patients (
    patient_id TEXT PRIMARY KEY,
    document_json TEXT NOT NULL
);
CREATE TABLE plans (
    plan_id TEXT PRIMARY KEY,
    patient_id TEXT NOT NULL,
    envelope_id TEXT NOT NULL,
    envelope_version INTEGER NOT NULL,
    engine TEXT,
    feasible INTEGER NOT NULL,
    violation_count INTEGER NOT NULL DEFAULT 0,
    objectives_json TEXT,
    days_json TEXT,
    adequacy_json TEXT,
    kb_version TEXT,
    document_json TEXT,
    created_at TEXT NOT NULL
);
CREATE INDEX idx_plans_patient ON plans(patient_id, created_at);
CREATE TABLE meal_logs (
    patient_id TEXT NOT NULL,
    date TEXT NOT NULL,
    meal TEXT NOT NULL,
    dish_id TEXT NOT NULL,
    logged_at TEXT NOT NULL,
    items_json TEXT,
    PRIMARY KEY (patient_id, date, meal)
);
CREATE INDEX idx_meal_logs_patient_date ON meal_logs(patient_id, date);
CREATE TABLE envelope_journal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event TEXT,
    envelope_id TEXT NOT NULL,
    patient_id TEXT NOT NULL,
    version INTEGER NOT NULL,
    status TEXT NOT NULL,
    snapshot_json TEXT NOT NULL,
    effective_at TEXT NOT NULL
);
CREATE INDEX idx_journal_patient_effective ON envelope_journal(patient_id, effective_at);
CREATE INDEX idx_journal_envelope ON envelope_journal(envelope_id);
CREATE TABLE observations (
    observation_id TEXT PRIMARY KEY,
    patient_id TEXT NOT NULL,
    metric TEXT NOT NULL,
    value DOUBLE PRECISION NOT NULL,
    unit TEXT,
    source TEXT,
    observed_at TEXT NOT NULL,
    recorded_at TEXT NOT NULL
);
CREATE INDEX idx_observations_patient ON observations(patient_id, observed_at);
CREATE TABLE simulations (
    simulation_id TEXT PRIMARY KEY,
    patient_id TEXT NOT NULL,
    base_envelope_id TEXT NOT NULL,
    proposed_targets_json TEXT NOT NULL,
    comparison_json TEXT,
    status TEXT NOT NULL DEFAULT 'OPEN',
    created_at TEXT NOT NULL
);
CREATE INDEX idx_simulations_patient ON simulations(patient_id, created_at);
CREATE TABLE review_items (
    review_id TEXT PRIMARY KEY,
    patient_id TEXT NOT NULL,
    source TEXT NOT NULL,
    payload_json TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'OPEN',
    created_at TEXT NOT NULL,
    acknowledged_at TEXT,
    action_json TEXT,
    linked_envelope_id TEXT
);
CREATE INDEX idx_review_status ON review_items(status, created_at);
CREATE INDEX idx_review_patient ON review_items(patient_id);
